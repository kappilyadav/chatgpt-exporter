#!/usr/bin/env python3
"""Build the translation files from the sources in scripts/i18n/.

Usage:  python3 scripts/build_locales.py          (run from anywhere; --check validates without writing)

Source:  scripts/i18n/<locale>.json      flat {"key": "text"} files; en.json is the master list of keys.
Output:  _locales/<locale>/messages.json  Chrome's format (manifest name/description and Web Store listing);
         _locales/nb and _locales/iw are copies of no and he (other codes for the same languages)
         src/core/locales.js              every locale bundled for the content scripts, popup, options and print page

Validation (fails the build): every locale has exactly the keys of en.json, {placeholders} match en.json,
no "$" (Chrome treats it as a placeholder marker), the store name is <= 75 chars and the summary <= 132 chars.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'scripts', 'i18n')
OUT_LOCALES = os.path.join(ROOT, '_locales')
OUT_JS = os.path.join(ROOT, 'src', 'core', 'locales.js')

# Locale codes Chrome accepts for _locales folders.
CHROME_CODES = set('''ar am bg bn ca cs da de el en en_AU en_GB en_US es es_419 et fa fi fil fr gu he hi hr hu id it ja kn ko
lt lv ml mr ms nl no pl pt_BR pt_PT ro ru sk sl sr sv sw ta te th tr uk vi zh_CN zh_TW'''.split())
# Chrome reports Norwegian Bokmål as "nb" while the Web Store lists Norwegian as "no": ship both folders.
# The Web Store dashboard still calls Hebrew "iw" (the old code), so ship that folder too.
ALIAS_FOLDERS = {'nb': 'no', 'iw': 'he'}
MANIFEST_ONLY = re.compile(r'^(ext|cmd)[A-Z]')  # only the manifest needs these; keep them out of the runtime bundle
LIMITS = {'extName': 75, 'extDescription': 132}
PH = re.compile(r'\{(\w+)\}')


def load(code):
    with open(os.path.join(SRC, code + '.json'), encoding='utf-8') as f:
        return json.load(f)


def main():
    check_only = '--check' in sys.argv
    codes = sorted(n[:-5] for n in os.listdir(SRC) if n.endswith('.json'))
    if 'en' not in codes:
        sys.exit('scripts/i18n/en.json (the master list) is missing')
    en = load('en')
    problems = []
    data = {}
    for code in codes:
        if code not in CHROME_CODES:
            problems.append('%s: not a Chrome locale code' % code)
        d = load(code)
        data[code] = d
        missing = [k for k in en if k not in d]
        extra = [k for k in d if k not in en]
        if missing:
            problems.append('%s: missing %d keys (%s...)' % (code, len(missing), ', '.join(missing[:5])))
        if extra:
            problems.append('%s: unknown keys (%s)' % (code, ', '.join(extra[:5])))
        for k, v in d.items():
            if k not in en:
                continue
            if not isinstance(v, str) or not v.strip():
                problems.append('%s.%s: empty' % (code, k))
                continue
            if '$' in v:
                problems.append('%s.%s: contains "$"' % (code, k))
            if sorted(PH.findall(v)) != sorted(PH.findall(en[k])):
                problems.append('%s.%s: placeholders %s differ from en %s' % (code, k, PH.findall(v), PH.findall(en[k])))
            if k in LIMITS and len(v) > LIMITS[k]:
                problems.append('%s.%s: %d chars, limit is %d' % (code, k, len(v), LIMITS[k]))
    if problems:
        print('\n'.join(problems))
        sys.exit('%d problem(s)' % len(problems))
    print('%d locales x %d keys OK' % (len(codes), len(en)))
    if check_only:
        return

    for code in codes:
        os.makedirs(os.path.join(OUT_LOCALES, code), exist_ok=True)
        msgs = {k: {'message': data[code][k]} for k in en}
        with open(os.path.join(OUT_LOCALES, code, 'messages.json'), 'w', encoding='utf-8') as f:
            json.dump(msgs, f, ensure_ascii=False, indent=2)
            f.write('\n')

    for alias, target in ALIAS_FOLDERS.items():
        os.makedirs(os.path.join(OUT_LOCALES, alias), exist_ok=True)
        shutil.copyfile(os.path.join(OUT_LOCALES, target, 'messages.json'), os.path.join(OUT_LOCALES, alias, 'messages.json'))

    runtime = {c: {k: v for k, v in data[c].items() if not MANIFEST_ONLY.match(k)} for c in codes}
    with open(OUT_JS, 'w', encoding='utf-8') as f:
        f.write('/* GENERATED by scripts/build_locales.py from scripts/i18n/*.json. Do not edit by hand. */\n')
        f.write('(globalThis.CE = globalThis.CE || {}).LOCALES = ')
        json.dump(runtime, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')
    print('wrote _locales/ and src/core/locales.js (%d KB)' % (os.path.getsize(OUT_JS) // 1024))


if __name__ == '__main__':
    main()
